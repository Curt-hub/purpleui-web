export function hexToHsl(hex: string): { h: number; s: number; l: number } {
  const h = hex.replace('#', '');
  const r = parseInt(h.slice(0, 2), 16) / 255;
  const g = parseInt(h.slice(2, 4), 16) / 255;
  const b = parseInt(h.slice(4, 6), 16) / 255;

  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;

  if (max === min) return { h: 0, s: 0, l: l * 100 };

  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);

  let hue: number;
  switch (max) {
    case r: hue = ((g - b) / d + (g < b ? 6 : 0)) / 6; break;
    case g: hue = ((b - r) / d + 2) / 6; break;
    default: hue = ((r - g) / d + 4) / 6;
  }

  return { h: hue * 360, s: s * 100, l: l * 100 };
}

export function hslToHex(h: number, s: number, l: number): string {
  const sn = s / 100;
  const ln = l / 100;
  const c = (1 - Math.abs(2 * ln - 1)) * sn;
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = ln - c / 2;

  let r = 0, g = 0, b = 0;
  if      (h < 60)  { r = c; g = x; b = 0; }
  else if (h < 120) { r = x; g = c; b = 0; }
  else if (h < 180) { r = 0; g = c; b = x; }
  else if (h < 240) { r = 0; g = x; b = c; }
  else if (h < 300) { r = x; g = 0; b = c; }
  else              { r = c; g = 0; b = x; }

  const hex = (v: number) => Math.round((v + m) * 255).toString(16).padStart(2, '0');
  return `#${hex(r)}${hex(g)}${hex(b)}`;
}

// Blend each RGB channel towards white by `amount` (0–1).
// Matches the Brand Guidelines page formula exactly.
export function lightenHex(hex: string, amount: number): string {
  const h = hex.replace('#', '');
  const r = parseInt(h.slice(0, 2), 16);
  const g = parseInt(h.slice(2, 4), 16);
  const b = parseInt(h.slice(4, 6), 16);
  return '#' + [r, g, b]
    .map(c => Math.min(255, Math.round(c + (255 - c) * amount)).toString(16).padStart(2, '0'))
    .join('');
}

export function hexToRgba(hex: string, alpha: number): string {
  const h = hex.replace('#', '');
  const r = parseInt(h.slice(0, 2), 16);
  const g = parseInt(h.slice(2, 4), 16);
  const b = parseInt(h.slice(4, 6), 16);
  return `rgba(${r},${g},${b},${alpha})`;
}

export type LogoOrientation = 'landscape' | 'square' | 'portrait';

export function getLogoOrientation(width: number, height: number): LogoOrientation {
  const ratio = width / height;
  if (ratio >= 1.5) return 'landscape';
  if (ratio >= 0.75) return 'square';
  return 'portrait';
}

export function getLogoMaxDims(orientation: LogoOrientation): { maxW: number; maxH: number } {
  switch (orientation) {
    case 'landscape': return { maxW: 160, maxH: 50 };
    case 'square':    return { maxW: 70,  maxH: 70 };
    case 'portrait':  return { maxW: 55,  maxH: 90 };
  }
}

